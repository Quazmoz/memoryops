import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const openapiPath = resolve(repoRoot, "docs/openapi.yaml");
const outputPath = resolve(repoRoot, "frontend/src/api/generated/contract.ts");
const checkOnly = process.argv.includes("--check");

const openapi = readFileSync(openapiPath, "utf8");
const operations = extractOperations(openapi);
const output = renderContract(operations);

if (checkOnly) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== output) {
    console.error("Generated API contract is out of date. Run `npm run generate:api` in frontend/.");
    process.exit(1);
  }
  console.log(`Generated API contract is up to date (${operations.length} operations).`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${operations.length} operations to ${outputPath}`);
}

function extractOperations(source) {
  const lines = source.split(/\r?\n/);
  const operations = [];
  let inPaths = false;
  let currentPath = null;
  let currentMethod = null;

  for (const line of lines) {
    if (line === "paths:") {
      inPaths = true;
      continue;
    }
    if (inPaths && line === "components:") {
      break;
    }
    if (!inPaths) {
      continue;
    }

    const pathMatch = line.match(/^  (\/[^:]+):\s*$/);
    if (pathMatch) {
      currentPath = pathMatch[1];
      currentMethod = null;
      continue;
    }

    const methodMatch = line.match(/^    (get|post|patch|delete|put):\s*$/);
    if (methodMatch) {
      currentMethod = methodMatch[1];
      continue;
    }

    const operationMatch = line.match(/^      operationId:\s*([A-Za-z0-9_]+)\s*$/);
    if (operationMatch && currentPath && currentMethod) {
      operations.push({
        id: operationMatch[1],
        method: currentMethod,
        path: currentPath,
      });
    }
  }

  const ids = new Set();
  for (const operation of operations) {
    if (ids.has(operation.id)) {
      throw new Error(`Duplicate operationId in OpenAPI contract: ${operation.id}`);
    }
    ids.add(operation.id);
  }

  return operations;
}

function renderContract(operations) {
  const operationLines = operations
    .map(
      (operation) =>
        `  ${JSON.stringify(operation.id)}: { method: ${JSON.stringify(operation.method)}, path: ${JSON.stringify(operation.path)} },`,
    )
    .join("\n");

  return `/* eslint-disable */
// This file is generated by scripts/generate-openapi-client.mjs from docs/openapi.yaml.
// Do not edit it by hand.

import { apiRequest } from "../client";
import type { JsonValue } from "../types";

export const apiOperations = {
${operationLines}
} as const;

export type ApiOperationId = keyof typeof apiOperations;
export type ApiOperation = (typeof apiOperations)[ApiOperationId];
export type ApiMethod = ApiOperation["method"];
export type ApiPath = ApiOperation["path"];

export type ApiContractRequestOptions = Omit<RequestInit, "body" | "method"> & {
  auth?: boolean;
  body?: JsonValue;
  path?: string;
};

export function operationPath(operationId: ApiOperationId): ApiPath {
  return apiOperations[operationId].path;
}

export function operationMethod(operationId: ApiOperationId): ApiMethod {
  return apiOperations[operationId].method;
}

export function resolveOperationPath(
  operationId: ApiOperationId,
  params: Record<string, string | number | boolean>,
): string {
  return operationPath(operationId).replace(/\\{([^}]+)\\}/g, (_match, name: string) => {
    const value = params[name];
    if (value === undefined) {
      throw new Error(\`Missing OpenAPI path parameter: \${name}\`);
    }
    return encodeURIComponent(String(value));
  });
}

export function apiContractRequest<TResponse = JsonValue>(
  operationId: ApiOperationId,
  options: ApiContractRequestOptions = {},
): Promise<TResponse> {
  const operation = apiOperations[operationId];
  const { path, ...requestOptions } = options;
  return apiRequest<TResponse>(path ?? operation.path, {
    ...requestOptions,
    method: operation.method.toUpperCase(),
  });
}
`;
}